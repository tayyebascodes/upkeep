"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { Plus } from "lucide-react";
import { createClient } from "@/lib/supabase/client";
import { Field, FormError } from "@/components/auth/Field";

export function AddPropertyForm({ companyId }: { companyId: string }) {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const handleSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    const form = new FormData(e.currentTarget);
    setLoading(true);
    setError(null);

    // Slug is generated by a database trigger.
    const { error } = await createClient()
      .from("properties")
      .insert({
        company_id: companyId,
        name: String(form.get("name")).trim(),
        address: String(form.get("address") || "").trim() || null,
        slug: "",
      });

    setLoading(false);
    if (error) return setError(error.message);
    setOpen(false);
    router.refresh();
  };

  if (!open) {
    return (
      <button
        onClick={() => setOpen(true)}
        className="flex min-h-[220px] flex-col items-center justify-center gap-2 rounded-2xl border border-dashed border-brand-200 text-sm font-medium text-brand-700 transition hover:border-brand-400 hover:bg-brand-50/50"
      >
        <Plus className="h-5 w-5" />
        Add property
      </button>
    );
  }

  return (
    <form onSubmit={handleSubmit} className="card space-y-4 p-6">
      <h2 className="font-medium">New property</h2>
      <Field label="Name" name="name" required autoFocus />
      <Field label="Address" name="address" hint="Optional" />
      <FormError message={error} />
      <div className="flex gap-2">
        <button type="submit" disabled={loading} className="btn btn-primary">
          {loading ? "Adding…" : "Add"}
        </button>
        <button type="button" onClick={() => setOpen(false)} className="btn btn-ghost">
          Cancel
        </button>
      </div>
    </form>
  );
}
